/**
 * Deterministic assessment coverage report generator (Node, no dependencies).
 *
 * Reads the live bank (data/assessments.json) and the live topic manifest
 * (built from data/curriculum.json plus content markdown via the canonical
 * builders) and writes docs/assessment-coverage.md. Output is fully
 * reproducible: sorted inputs, no timestamps, trailing newline. Never edit
 * the markdown by hand — regenerate with:
 *
 *   node scripts/generate-assessment-coverage.js
 *
 * The report states totals, per-course/per-module coverage, exam-relevant
 * coverage, type distribution, single/multi-question topics, and remaining
 * gaps. Uncovered topics are listed as without questions and never implied
 * to be assessed. No quality scores, ever.
 */
import fs from 'node:fs';
import path from 'node:path';
import { loadCurriculum } from './curriculum.js';
import { loadTopicSchema } from './topic-metadata.js';
import { buildTopicManifest } from './topic-manifest.js';
import {
  getAssessmentCoverage,
  getAssessmentQuestionCount,
  getQuestionsPerCourse,
  getCoveredTopicsPerCourse,
  getQuestionsPerModule,
  getTopicQuestionCounts,
  getSingleQuestionTopics,
  getMultiQuestionTopics,
  getExamQuestionCoverage,
  getQuestionTypeDistribution,
} from './assessment.js';

export const COVERAGE_REPORT_PATH = path.join('docs', 'assessment-coverage.md');

function pad(value, width) {
  const s = String(value);
  return s.length >= width ? s : s + ' '.repeat(width - s.length);
}

export function buildCoverageReport({ bank, manifest }) {
  const coverage = getAssessmentCoverage(bank, manifest);
  const totalQuestions = getAssessmentQuestionCount(bank);
  const perCourse = getQuestionsPerCourse(bank);
  const coveredPerCourse = getCoveredTopicsPerCourse(bank, manifest);
  const perModule = getQuestionsPerModule(bank, manifest);
  const typeDist = getQuestionTypeDistribution(bank);
  const examCov = getExamQuestionCoverage(bank, manifest);
  const counts = getTopicQuestionCounts(bank, manifest);
  const single = getSingleQuestionTopics(bank, manifest);
  const multi = getMultiQuestionTopics(bank, manifest);

  const coveragePct = coverage.totalTopics
    ? Math.round((coverage.coveredCount / coverage.totalTopics) * 100)
    : 0;

  const lines = [];
  lines.push('# Assessment Coverage Report');
  lines.push('');
  lines.push('> Deterministic snapshot of the live question bank over the live topic manifest.');
  lines.push('> Generated by `node scripts/generate-assessment-coverage.js` — do not edit by hand.');
  lines.push('> Uncovered topics have no questions and are not assessed; this report never implies otherwise.');
  lines.push('');
  lines.push('## Totals');
  lines.push('');
  lines.push(`- Questions: ${totalQuestions}`);
  lines.push(`- Covered topics: ${coverage.coveredCount} of ${coverage.totalTopics} (${coveragePct}%)`);
  lines.push(`- Uncovered topics: ${coverage.uncoveredTopics.length} (without questions — not assessed)`);
  lines.push(`- Exam-relevant coverage: ${examCov.coveredExamTopics} of ${examCov.totalExamTopics} (${examCov.coverage}%)`);
  lines.push(`- Single-question topics: ${single.length}`);
  lines.push(`- Multi-question topics: ${multi.length}`);
  lines.push('');
  lines.push('## Question-type distribution');
  lines.push('');
  lines.push('| Type | Count |');
  lines.push('| --- | ---: |');
  lines.push(`| multiple_choice | ${typeDist.multiple_choice} |`);
  lines.push(`| true_false | ${typeDist.true_false} |`);
  lines.push(`| short_answer | ${typeDist.short_answer} |`);
  lines.push('');
  lines.push('## Per-course coverage');
  lines.push('');
  lines.push('| Course | Questions | Covered topics | Total topics | Uncovered |');
  lines.push('| --- | ---: | ---: | ---: | ---: |');
  const perCourseMap = new Map(perCourse.map((r) => [r.courseCode, r.questionCount]));
  for (const row of coveredPerCourse) {
    lines.push(`| ${row.courseCode} | ${perCourseMap.get(row.courseCode) || 0} | ${row.coveredCount} | ${row.totalTopics} | ${row.uncoveredCount} |`);
  }
  lines.push('');
  lines.push('## Per-module questions');
  lines.push('');
  lines.push('| Course | Module | Module name | Questions |');
  lines.push('| --- | ---: | --- | ---: |');
  for (const row of perModule) {
    lines.push(`| ${row.courseCode} | ${row.module} | ${row.moduleName} | ${row.questionCount} |`);
  }
  lines.push('');
  lines.push('## Exam-relevant coverage');
  lines.push('');
  lines.push(`- Exam-relevant topics in manifest: ${examCov.totalExamTopics}`);
  lines.push(`- Exam-relevant topics with questions: ${examCov.coveredExamTopics}`);
  lines.push(`- Exam-relevant topics without questions: ${examCov.uncoveredExamTopics} (not assessed)`);
  lines.push(`- Coverage: ${examCov.coverage}%`);
  lines.push('');
  lines.push('## Single- vs multi-question topics');
  lines.push('');
  lines.push(`- Topics with exactly 1 question: ${single.length}`);
  lines.push(`- Topics with more than 1 question: ${multi.length}`);
  if (single.length) {
    lines.push('');
    lines.push('Single-question topics (course/topic):');
    lines.push('');
    for (const t of single) lines.push(`- ${t.courseCode}/${t.id}`);
  }
  lines.push('');
  lines.push('Question counts use bank order for covered topics and manifest order for uncovered topics.');
  lines.push(`Covered topics: ${counts.length} listed in the bank; each carries ${counts.length ? counts[0].questionCount : 0}–${counts.reduce((m, r) => Math.max(m, r.questionCount), 0)} questions in this snapshot.`);
  lines.push('');
  lines.push('## Remaining gaps');
  lines.push('');
  lines.push(`- ${coverage.uncoveredTopics.length} topics have no questions and are therefore not assessed.`);
  lines.push('- Uncovered counts per course:');
  lines.push('');
  for (const row of coveredPerCourse) {
    lines.push(`  - ${row.courseCode}: ${row.uncoveredCount} uncovered of ${row.totalTopics}`);
  }
  lines.push('');
  lines.push('Gaps are informational only: nothing is locked or gated, and uncovered topics remain fully readable.');
  lines.push('');
  return `${lines.join('\n')}\n`;
}

export function generateCoverageReport(outputPath = COVERAGE_REPORT_PATH) {
  const curriculumDoc = loadCurriculum();
  const schema = loadTopicSchema();
  const manifest = buildTopicManifest({ curriculumDoc, schema });
  const bank = JSON.parse(fs.readFileSync(path.join('data', 'assessments.json'), 'utf-8'));
  const markdown = buildCoverageReport({ bank, manifest });
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, markdown, 'utf-8');
  return { outputPath, manifest, bank, markdown };
}

const isMain = process.argv[1] && process.argv[1].endsWith('generate-assessment-coverage.js');
if (isMain) {
  const { outputPath, bank, manifest } = generateCoverageReport();
  const coverage = getAssessmentCoverage(bank, manifest);
  console.log(`assessment coverage: ${coverage.totalQuestions} questions, ${coverage.coveredCount} covered topics, ${coverage.uncoveredTopics.length} uncovered topics -> ${outputPath}`);
}
